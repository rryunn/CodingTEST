-- 리뷰를 가장 많이 작성한 회원의 리뷰 
-- 리뷰가 최대인 사람의 수를 먼저 구하고
-- 그 값을 가진 사람을 리턴하면 될듯

SELECT M.MEMBER_NAME, R.REVIEW_TEXT, 
DATE_FORMAT(R.REVIEW_DATE, "%Y-%m-%d") AS REVIEW_DATE
FROM REST_REVIEW R
JOIN MEMBER_PROFILE M ON M.MEMBER_ID = R.MEMBER_ID
WHERE M.MEMBER_ID =(
    SELECT MEMBER_ID
    FROM REST_REVIEW 
    GROUP BY MEMBER_ID
    ORDER BY COUNT(*) DESC
    LIMIT 1)
ORDER BY REVIEW_DATE, R.REVIEW_TEXT