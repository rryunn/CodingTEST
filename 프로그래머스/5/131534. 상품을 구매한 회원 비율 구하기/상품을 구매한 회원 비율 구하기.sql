-- 상품 구매한 회원 수 
-- 상품을 구매한 회원의 비율 (가입한 전체 회원 대비)
-- ROUND 2

SELECT YEAR(O.SALES_DATE) AS YEAR, MONTH(O.SALES_DATE) AS MONTH, COUNT(DISTINCT(O.USER_ID)) AS PURCHASED_USERS, 
ROUND(
    COUNT(DISTINCT(O.USER_ID))/(SELECT COUNT(*) FROM USER_INFO WHERE YEAR(JOINED)=2021),1) 
    AS PUCHASED_RATIO
FROM ONLINE_SALE O
JOIN USER_INFO U ON U.USER_ID = O.USER_ID
WHERE U.JOINED>='2021-01-01' AND U.JOINED<'2022-01-01'
GROUP BY YEAR,MONTH
ORDER BY YEAR, MONTH
